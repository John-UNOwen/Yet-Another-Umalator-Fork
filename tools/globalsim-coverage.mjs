// GlobalSim skill coverage report + active-table merge (Phase 2 of the
// GlobalSim integration plan).
//
//   node tools/globalsim-coverage.mjs [--write] [--out merged.json]
//
//   active table   = vendor/GlobalSim/data/v70-skill-data.json (validated)
//                    ∪ globalsim/skills-supplement.json (fork batches)
//   missing        = umalator-global/skill_data.json keys − active keys,
//                    split into live-on-Global vs listed in not-in-game.json,
//                    each with the skill name and whether GlobalSim's legacy
//                    built-in table holds a definition identical to uma-tools'.
//
// --write commits the report to globalsim/coverage-report.md.
// --out also writes the merged active table (site build input).
// With neither flag the tool writes NOTHING and only prints the report — that
// gate mode is what CI runs (`npm run globalsim:coverage`).
// Exit 1 when a live-on-Global skill is uncovered, the supplement is
// malformed, or the supplement overwrites a v70 entry (CI gate after every
// upstream data sync).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));

const umaSkills = read('umalator-global/skill_data.json');
const umaNames = read('umalator-global/skillnames.json');
const notInGame = new Set(read('umalator-global/not-in-game.json').skills);
const v70 = read('vendor/GlobalSim/data/v70-skill-data.json');
const legacy = read('vendor/GlobalSim/data/skill_data.json');
const supplementPath = 'globalsim/skills-supplement.json';
const supplement = fs.existsSync(path.join(root, supplementPath)) ? read(supplementPath) : {};

const canon = (v) => {
  if (Array.isArray(v)) return v.map(canon);
  if (v && typeof v === 'object') return Object.fromEntries(Object.keys(v).sort().map((k) => [k, canon(v[k])]));
  return v;
};
const canonText = (v) => JSON.stringify(canon(v));

// isGeneralSkill per the validated v70 table: unique skills (IDs starting with
// 1) and support-card skills (3…) are false; regulars (2…) and inherited
// uniques (9…) are true. priority is 0 for every v70 entry.
const isGeneralRule = (id) => !(id[0] === '1' || id[0] === '3');

const errors = [];
const warnings = [];

// ── Supplement validation ────────────────────────────────────────────────────
for (const [id, def] of Object.entries(supplement)) {
  if (!/^\d+$/.test(id)) errors.push(`supplement: id "${id}" is not numeric`);
  if (v70[id]) errors.push(`supplement: ${id} would overwrite a v70 entry — batches only ADD skills`);
  if (!Array.isArray(def.alternatives) || def.alternatives.length === 0) errors.push(`supplement ${id}: needs a non-empty alternatives array`);
  if (typeof def.rarity !== 'number') errors.push(`supplement ${id}: rarity must be a number`);
  if (def.isGeneralSkill !== true && def.isGeneralSkill !== false) errors.push(`supplement ${id}: isGeneralSkill must be explicit (the legacy default of true flips semantics for 1…/3… ids)`);
  else if (def.isGeneralSkill !== isGeneralRule(id)) warnings.push(`supplement ${id}: isGeneralSkill=${def.isGeneralSkill} deviates from the v70 pattern (${isGeneralRule(id)}) — check the official master flag`);
  if (def.priority !== 0 && def.priority !== 1) errors.push(`supplement ${id}: priority must be 0 or 1 (v70 uses only 0)`);
  if (!(id in umaSkills)) errors.push(`supplement ${id}: not in umalator-global/skill_data.json — batches must match current uma-tools data`);
  else {
    const { isGeneralSkill: g, priority: p, ...rest } = def;
    if (canonText(rest) !== canonText(umaSkills[id])) errors.push(`supplement ${id}: definition differs from umalator-global/skill_data.json — port from uma-tools, then only add priority/isGeneralSkill`);
  }
}

// ── Active table + merge ─────────────────────────────────────────────────────
const active = { ...v70, ...supplement };

// ── Missing report ───────────────────────────────────────────────────────────
const missing = Object.keys(umaSkills).filter((id) => !(id in active));
const missingLive = [];
const missingNotInGame = [];
for (const id of missing) {
  const name = umaNames[id]?.[0] ?? '?';
  const legacyDef = legacy[id];
  const row = { id, name, legacy: legacyDef ? (canonText(legacyDef) === canonText(umaSkills[id]) ? 'equal' : 'DIFFERS') : 'absent' };
  (notInGame.has(id) ? missingNotInGame : missingLive).push(row);
}

// ── Output ───────────────────────────────────────────────────────────────────
const outArg = process.argv.indexOf('--out');
if (outArg >= 0) fs.writeFileSync(path.resolve(process.argv[outArg + 1]), JSON.stringify(active) + '\n');

const lines = [
  '# GlobalSim skill coverage',
  '',
  `Generated by \`node tools/globalsim-coverage.mjs --write\` (npm run globalsim:coverage:write). Do not edit by hand.`,
  '',
  `- uma-tools Global skills: **${Object.keys(umaSkills).length}**`,
  `- GlobalSim validated table (v70): **${Object.keys(v70).length}**`,
  `- fork supplement batches: **${Object.keys(supplement).length}**`,
  `- active table: **${Object.keys(active).length}**`,
  `- missing, live on Global (must be 0): **${missingLive.length}**`,
  `- missing, listed in not-in-game.json (JP fast-forwards): **${missingNotInGame.length}**`,
  '',
  `## Missing and live on Global — add a batch`,
  '',
];
if (missingLive.length === 0) lines.push('None. Every live Global skill is in the active table.');
else {
  lines.push('| id | name | GlobalSim legacy def |', '|---|---|---|');
  for (const r of missingLive) lines.push(`| ${r.id} | ${r.name} | ${r.legacy} |`);
}
lines.push('', '## Missing and not-in-game (added back as Global catches up)', '',
  '| id | name | GlobalSim legacy def |', '|---|---|---|');
for (const r of missingNotInGame) lines.push(`| ${r.id} | ${r.name} | ${r.legacy} |`);
const reportText = lines.join('\n') + '\n';

if (process.argv.includes('--write')) {
  fs.mkdirSync(path.join(root, 'globalsim'), { recursive: true });
  fs.writeFileSync(path.join(root, 'globalsim/coverage-report.md'), reportText);
  console.log(`wrote globalsim/coverage-report.md`);
} else {
  console.log(reportText);
}
for (const w of warnings) console.log(`WARN ${w}`);
for (const e of errors) console.log(`ERROR ${e}`);
if (missingLive.length) console.log(`ERROR ${missingLive.length} live-on-Global skill(s) are not covered by the active table`);
const fail = errors.length || missingLive.length;
console.log(fail ? 'COVERAGE: FAIL' : 'COVERAGE: OK');
process.exitCode = fail ? 1 : 0;
